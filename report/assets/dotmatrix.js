/* 5x7 dot-matrix font drawn as SVG circles. No font files. Characters: A-Z 0-9 . / : % - + x and space. */
(function (g) {
  const F = {
    A: "01110 10001 10001 11111 10001 10001 10001", B: "11110 10001 10001 11110 10001 10001 11110",
    C: "01110 10001 10000 10000 10000 10001 01110", D: "11110 10001 10001 10001 10001 10001 11110",
    E: "11111 10000 10000 11110 10000 10000 11111", F: "11111 10000 10000 11110 10000 10000 10000",
    G: "01110 10001 10000 10111 10001 10001 01111", H: "10001 10001 10001 11111 10001 10001 10001",
    I: "01110 00100 00100 00100 00100 00100 01110", J: "00111 00010 00010 00010 00010 10010 01100",
    K: "10001 10010 10100 11000 10100 10010 10001", L: "10000 10000 10000 10000 10000 10000 11111",
    M: "10001 11011 10101 10101 10001 10001 10001", N: "10001 10001 11001 10101 10011 10001 10001",
    O: "01110 10001 10001 10001 10001 10001 01110", P: "11110 10001 10001 11110 10000 10000 10000",
    Q: "01110 10001 10001 10001 10101 10010 01101", R: "11110 10001 10001 11110 10100 10010 10001",
    S: "01111 10000 10000 01110 00001 00001 11110", T: "11111 00100 00100 00100 00100 00100 00100",
    U: "10001 10001 10001 10001 10001 10001 01110", V: "10001 10001 10001 10001 10001 01010 00100",
    W: "10001 10001 10001 10101 10101 10101 01010", X: "10001 10001 01010 00100 01010 10001 10001",
    Y: "10001 10001 01010 00100 00100 00100 00100", Z: "11111 00001 00010 00100 01000 10000 11111",
    0: "01110 10001 10011 10101 11001 10001 01110", 1: "00100 01100 00100 00100 00100 00100 01110",
    2: "01110 10001 00001 00010 00100 01000 11111", 3: "11111 00010 00100 00010 00001 10001 01110",
    4: "00010 00110 01010 10010 11111 00010 00010", 5: "11111 10000 11110 00001 00001 10001 01110",
    6: "00110 01000 10000 11110 10001 10001 01110", 7: "11111 00001 00010 00100 01000 01000 01000",
    8: "01110 10001 10001 01110 10001 10001 01110", 9: "01110 10001 10001 01111 00001 00010 01100",
    ".": "00 00 00 00 00 11 11", ":": "00 11 11 00 11 11 00", "/": "00000 00001 00010 00100 01000 10000 00000",
    "%": "11000 11001 00010 00100 01000 10011 00011", "-": "0000 0000 0000 1111 0000 0000 0000",
    "+": "00000 00100 00100 11111 00100 00100 00000", x: "00000 00000 10001 01010 00100 01010 10001",
    " ": "000 000 000 000 000 000 000"
  };
  const G = {};
  for (const k in F) G[k] = F[k].split(" ");
  function glyph(ch) { return G[ch] || G[String(ch).toUpperCase()] || G[" "]; }

  /** Returns {w, h, dots:[[x,y],...]} in dot units (1 column gap between glyphs). */
  function layout(text) {
    const dots = []; let x = 0;
    const s = String(text);
    for (let i = 0; i < s.length; i++) {
      const ch = s[i] === "x" ? "x" : s[i];
      const rows = glyph(ch);
      for (let r = 0; r < 7; r++) for (let c = 0; c < rows[r].length; c++) if (rows[r][c] === "1") dots.push([x + c, r]);
      x += rows[0].length + (i < s.length - 1 ? 1 : 0);
    }
    return { w: x, h: 7, dots };
  }

  /** SVG string. opts: pitch (px per dot, default 6), r (radius ratio), label (aria), cls. */
  function svg(text, opts) {
    opts = opts || {};
    const p = opts.pitch || 6, rr = (opts.r || 0.38) * p, L = layout(text);
    const W = Math.max(1, L.w * p), H = L.h * p;
    let c = "";
    for (const [x, y] of L.dots) c += `<circle cx="${(x * p + p / 2).toFixed(1)}" cy="${(y * p + p / 2).toFixed(1)}" r="${rr.toFixed(2)}"/>`;
    const lab = opts.label == null ? String(text) : opts.label;
    return `<svg class="dm ${opts.cls || ""}" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="${String(lab).replace(/"/g, "&quot;")}">${c}</svg>`;
  }

  /** Circles only, positioned at (ox, oy) inside an existing SVG. */
  function group(text, ox, oy, pitch, r) {
    const p = pitch || 6, rr = (r || 0.38) * p, L = layout(text);
    let c = "";
    for (const [x, y] of L.dots) c += `<circle cx="${(ox + x * p + p / 2).toFixed(1)}" cy="${(oy + y * p + p / 2).toFixed(1)}" r="${rr.toFixed(2)}"/>`;
    return { svg: c, w: L.w * p, h: L.h * p };
  }

  g.DotMatrix = { svg, group, layout, width: (t, p) => layout(t).w * (p || 6) };
})(window);
